'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const levels = require(path.join(root, 'api/_levels.js'));
const page = fs.readFileSync(path.join(root, 'public/lesson-plans.html'), 'utf8');
const app = fs.readFileSync(path.join(root, 'public/app.js'), 'utf8');
const prompt = fs.readFileSync(path.join(root, 'prompts/ges-lesson-plans.md'), 'utf8');
const jhs = levels.LEVELS.find((level) => level.id === 'jhs');
assert.ok(jhs, 'JHS level must exist');
for (const cls of jhs.classes) assert.ok(page.includes('<option>' + cls + '</option>'), cls + ' must be selectable');
const start = page.indexOf('<select id="jhs-subject" name="subject">');
const end = page.indexOf('</select>', start);
assert.ok(start >= 0 && end > start, 'JHS subject selector must exist');
const subjectBlock = page.slice(start, end);
for (const subject of jhs.subjects) assert.ok(subjectBlock.includes('<option>' + subject + '</option>'), subject + ' must be selectable');
assert.ok(page.includes('name="term"'), 'Term selector must exist');
assert.ok(page.includes('name="week"'), 'Week selector must exist');
assert.ok(page.includes('name="catalogue" value="1"'), 'Catalogue form must request one-tap generation');
assert.ok(app.includes('subjectsOf(linkedClass).includes(linkedSubject)'), 'App must validate the linked subject');
assert.ok(app.includes('termsFor(linkedClass).includes(linkedTerm)'), 'App must validate the linked term');
assert.ok(app.includes('weeksFor(linkedClass).includes(linkedWeek)'), 'App must validate the linked week');
assert.ok(app.includes("state.params.mode = 'full'"), 'Catalogue must use the shared full lesson-package format');
assert.ok(app.includes('catalogueAuto = q.get(\'catalogue\') === \'1\''), 'App must detect one-shot catalogue generation');
assert.ok(app.includes('Create the complete weekly lesson plan package using GuidEd'), 'App must submit a complete package request automatically');
assert.ok(prompt.includes('# Lesson Metadata') && prompt.includes('## Lesson 1') && prompt.includes('## Lesson 2') && prompt.includes('## Study Notes') && prompt.includes('## BECE Practice') && prompt.includes('## Assessment Rubric'), 'Shared JHS output format must include all standard sections');
console.log('JHS one-tap shared lesson-package catalogue checks passed.');
