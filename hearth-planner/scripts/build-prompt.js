// Regenerates api/_prompt.js from prompts/ges-lesson-plans.md.
// Run after editing the prompt:  node scripts/build-prompt.js
const fs = require('fs');
const path = require('path');

const src = path.join(__dirname, '..', 'prompts', 'ges-lesson-plans.md');
const out = path.join(__dirname, '..', 'api', '_prompt.js');

let text = fs.readFileSync(src, 'utf8').replace(/\r\n/g, '\n');
text = text.replace(/^---\n[\s\S]*?\n---\n/, '').trim();   // drop the frontmatter

// The Lower Primary, Upper Primary and SHS profiles are written beside the JHS rules, but each request only
// carries its own level's profile, so a JHS request costs what it always did.
const levelsOut = path.join(__dirname, '..', 'api', '_prompt_levels.js');
const from = text.indexOf('### Level:'), to = text.indexOf('## Class size and resources');
const block = text.slice(from, to);
text = (text.slice(0, from) + text.slice(to)).trim();
const profiles = {};
block.split(/^(?=### Level: )/m).filter((x) => x.trim()).forEach((part) => {
  const id = /Lower Primary/.test(part.split('\n')[0]) ? 'lower' : /Upper Primary/.test(part.split('\n')[0]) ? 'upper' : /SHS/.test(part.split('\n')[0]) ? 'shs' : null;
  if (!id) throw new Error('Unknown level heading: ' + part.split('\n')[0]);
  profiles[id] = ('## Level profile\n\n' + part.replace(/^### /, '### ')).trim();
});
if (Object.keys(profiles).length !== 3) throw new Error('Expected 3 level profiles, found ' + Object.keys(profiles).length);
fs.writeFileSync(levelsOut, '// GENERATED by scripts/build-prompt.js from prompts/ges-lesson-plans.md. Do not edit by hand.\n' + "'use strict';\nmodule.exports = " + JSON.stringify(profiles) + ';\n');

fs.writeFileSync(
  out,
  '// GENERATED by scripts/build-prompt.js from prompts/ges-lesson-plans.md. Do not edit by hand.\n' +
  "'use strict';\nmodule.exports = " + JSON.stringify(text) + ';\n'
);
console.log('Wrote', path.relative(process.cwd(), out), '(' + text.length + ' chars)');
