// Builds public/schemes.js (browser) and api/_schemes.js (server) from data/schemes.json.
//   node scripts/build-schemes.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'data', 'schemes.json'), 'utf8'));

const src = `// GENERATED by scripts/build-schemes.js from data/schemes.json. Do not edit by hand.
(function (root) {
  'use strict';
  var DATA = ${JSON.stringify(data)};

  function classRows(subject, cls, term) {
    var s = DATA.subjects[subject];
    var c = s && s.classes[cls];
    return c && c[String(term)] ? c[String(term)] : null;
  }
  function topicOf(x) {
    return x.strand ? x.strand + (x.substrand ? ' > ' + x.substrand : '') : x.indicators[0] || x.focus || '';
  }
  function teachRows(subject, cls, term) {
    return (classRows(subject, cls, term) || []).filter(function (x) { return x.type === 'teach'; });
  }

  // The Ghana school year: Term 1 starts in September, Term 2 in January and Term 3 around 20 April. August still counts as Term 3.
  function currentTerm(date) {
    var d = date || new Date(), m = d.getMonth() + 1, day = d.getDate();
    if (m >= 9) return 1;
    if (m <= 3 || (m === 4 && day < 20)) return 2;
    return 3;
  }

  // The scheme row for a subject, class, term and week, or null when none is loaded.
  // Returns { term, source, weeks, type: 'teach' | 'revision' | 'exam', strand, substrand, standard, indicators, focus, part, recall, topics }.
  function lookup(subject, cls, term, week) {
    var rows = classRows(subject, cls, term);
    if (!rows) return null;
    var meta = DATA.subjects[subject];
    for (var i = 0; i < rows.length; i++) {
      if (rows[i].weeks.indexOf(Number(week)) !== -1) {
        var r = rows[i];
        var out = { term: 'Term ' + term, termNo: Number(term), source: meta.source, weeks: r.weeks, type: r.type, strand: r.strand, substrand: r.substrand, standard: r.standard, indicators: r.indicators.slice(), focus: r.focus || '', part: r.part || null, recall: '', topics: [] };
        if (r.type === 'revision') {                 // the topics a revision week can draw on
          var from = r.weeks[0] === 1 ? Number(term) - 1 : Number(term);   // week 1 revises the term before, the later one revises this term
          if (from >= 1) teachRows(subject, cls, from).forEach(function (x) {
            var t = topicOf(x);
            if (t && out.topics.indexOf(t) === -1) out.topics.push(t);
          });
        } else if (r.type === 'teach') {             // the spiral: each week returns to the work just before it
          var prev = null;
          for (var j = i - 1; j >= 0 && !prev; j--) if (rows[j].type === 'teach') prev = rows[j];
          if (!prev && Number(term) > 1) { var before = teachRows(subject, cls, Number(term) - 1); prev = before[before.length - 1] || null; }
          var now = topicOf(r);
          if (prev && topicOf(prev) !== now) out.recall = topicOf(prev);
        }
        return out;
      }
    }
    return null;
  }
  // The last week the loaded scheme covers for a subject, class and term (0 when none).
  function span(subject, cls, term) {
    var rows = classRows(subject, cls, term);
    var max = 0;
    (rows || []).forEach(function (r) { r.weeks.forEach(function (w) { if (w > max) max = w; }); });
    return max;
  }

  // The lines that go into the request so the model plans from the real scheme.
  function describe(e) {
    if (!e) return [];
    var out = ['Scheme of learning (' + e.term + ', spiral progression, supplied by the school):'];
    if (e.type === 'revision') {
      if (e.weeks[0] === 1) {
        out.push('Week type: revision of the previous term. No new content. Plan two revision lessons on the key ideas from last term that this class needs before starting this term.');
        e.topics.forEach(function (t) { out.push('Topic taught last term: ' + t); });
      } else {
        out.push('Week type: revision of this term. No new content. Plan two revision lessons on the topics taught this term, so the class is ready for the examination:');
        e.topics.forEach(function (t) { out.push('Topic taught: ' + t); });
      }
      if (e.focus) out.push('Focus given by the school: ' + e.focus);
      return out;
    }
    out.push('Week type: teaching');
    if (e.strand) out.push('Strand: ' + e.strand);
    if (e.substrand) out.push('Sub-strand: ' + e.substrand);
    if (e.standard) out.push('Content Standard: ' + e.standard);
    if (e.recall) out.push('Spiral approach: open with a short recap of "' + e.recall + '" from the previous weeks and show how this week builds on it.');
    if (e.part) out.push('The school spreads this sub-strand over ' + e.part[1] + ' weeks and this is week ' + e.part[0] + ' of ' + e.part[1] + '. Plan only the part of the indicator that fits this week, build on the earlier weeks and do not repeat them.');
    e.indicators.forEach(function (x) { out.push('Indicator: ' + x); });
    if (!e.strand) out.push('The school gave only the indicator. Choose the NaCCA strand, sub-strand and content standard that match the indicator code, and write them in the metadata.');
    return out;
  }
  function has(subject, cls, term) { return !!classRows(subject, cls, term); }

  var api = { lookup: lookup, describe: describe, has: has, span: span, currentTerm: currentTerm };
  root.SchoolPadiSchemes = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
`;
for (const f of ['public/schemes.js', 'api/_schemes.js']) fs.writeFileSync(path.join(root, f), src);
const n = Object.values(data.subjects).reduce((a, s) => a + Object.keys(s).length, 0);
console.log('Wrote schemes.js and _schemes.js:', Object.keys(data.subjects).length, 'subjects,', n, 'class schemes,', data.term);
