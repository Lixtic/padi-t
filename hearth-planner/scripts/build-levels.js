// Copies api/_levels.js to public/levels.js so the browser and the server share one list.
// Run after editing api/_levels.js:  node scripts/build-levels.js
const fs = require('fs');
const path = require('path');
const src = path.join(__dirname, '..', 'api', '_levels.js');
const out = path.join(__dirname, '..', 'public', 'levels.js');
fs.writeFileSync(out, fs.readFileSync(src, 'utf8').replace("// SOURCE OF TRUTH. public/levels.js is generated from this file by `node scripts/build-levels.js`. Do not edit that copy.", '// GENERATED by scripts/build-levels.js from api/_levels.js. Do not edit by hand.').replace("'use strict';\n", "'use strict';\n"));
console.log('Wrote', path.relative(process.cwd(), out));
